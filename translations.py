def t(key, lang='zh'):
    """Get translation for a key in the given language."""
    entry = TRANSLATIONS.get(key)
    if not entry:
        return key
    return entry.get(lang, entry.get('zh', key))


def get_t(lang='zh'):
    """Return a translation function bound to a specific language."""
    def translate(key):
        return t(key, lang)
    return translate
